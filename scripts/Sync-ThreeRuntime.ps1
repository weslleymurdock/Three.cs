<#
.SYNOPSIS
    Copies the selected Three.js runtime files from the pinned lib/three.js submodule into the Three.cs RCL.

.DESCRIPTION
    The submodule is the only canonical source. This script copies the official upstream ESM build files
    (byte-for-byte), the upstream LICENSE, and regenerates the provenance metadata
    (wwwroot/three/upstream.json and wwwroot/js/three-upstream.js).
    It never changes the submodule revision. See docs/runtime/upstream.md.

.PARAMETER Check
    Verifies that the RCL copy and metadata are identical to what a sync would produce. Writes nothing.
    Exits with code 1 when any drift is found.

.EXAMPLE
    ./scripts/Sync-ThreeRuntime.ps1          # sync
    ./scripts/Sync-ThreeRuntime.ps1 -Check   # verify only
#>
[CmdletBinding()]
param(
    [switch]$Check
)

$ErrorActionPreference = 'Stop'

$repoRoot = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
$upstreamRoot = Join-Path $repoRoot 'lib/three.js'
$threeTarget = Join-Path $repoRoot 'src/Three.cs/wwwroot/three'
$jsTarget = Join-Path $repoRoot 'src/Three.cs/wwwroot/js'

# Selected upstream build files (see docs/runtime/upstream.md for the justification).
$selected = @(
    @{ Source = 'build/three.module.js'; Target = 'three.module.js' },
    @{ Source = 'build/three.core.js'; Target = 'three.core.js' }
)
$entryFile = 'three.module.js'

if (-not (Test-Path (Join-Path $upstreamRoot 'package.json'))) {
    throw "The lib/three.js submodule is not checked out. Run 'git submodule update --init lib/three.js'."
}

$commit = (& git -C $upstreamRoot rev-parse HEAD).Trim()
$describe = (& git -C $upstreamRoot describe --tags --always).Trim()
if ($LASTEXITCODE -ne 0 -or [string]::IsNullOrWhiteSpace($commit)) {
    throw 'Unable to read the lib/three.js revision with git.'
}

$package = Get-Content (Join-Path $upstreamRoot 'package.json') -Raw | ConvertFrom-Json
$version = $package.version
$license = $package.license
$repository = $package.repository.url

# REVISION constant exported by the shipped build (for example '187').
$moduleText = [System.IO.File]::ReadAllText((Join-Path $upstreamRoot 'build/three.core.js'))
$match = [regex]::Match($moduleText, "const REVISION = '(?<revision>[^']+)';")
if (-not $match.Success) {
    throw 'Unable to find the REVISION constant in build/three.core.js.'
}
$revision = $match.Groups['revision'].Value

$files = foreach ($item in $selected) {
    $sourcePath = Join-Path $upstreamRoot $item.Source
    if (-not (Test-Path $sourcePath)) { throw "Missing upstream file '$($item.Source)'." }
    $info = Get-Item $sourcePath
    [pscustomobject]@{
        Source = $item.Source
        Target = $item.Target
        SourcePath = $sourcePath
        Sha256 = (Get-FileHash $sourcePath -Algorithm SHA256).Hash.ToLowerInvariant()
        Bytes = $info.Length
    }
}
$licenseHash = (Get-FileHash (Join-Path $upstreamRoot 'LICENSE') -Algorithm SHA256).Hash.ToLowerInvariant()

$fileEntries = ($files | ForEach-Object {
        "    {`n      `"path`": `"$($_.Target)`",`n      `"source`": `"$($_.Source)`",`n      `"sha256`": `"$($_.Sha256)`",`n      `"bytes`": $($_.Bytes)`n    }"
    }) -join ",`n"

$json = @"
{
  "name": "three",
  "version": "$version",
  "revision": "$revision",
  "commit": "$commit",
  "describe": "$describe",
  "license": "$license",
  "licenseFile": "LICENSE",
  "licenseSha256": "$licenseHash",
  "repository": "$repository",
  "entry": "$entryFile",
  "files": [
$fileEntries
  ]
}

"@ -replace "`r`n", "`n"

$js = @"
// <auto-generated>
// Generated by scripts/Sync-ThreeRuntime.ps1 from wwwroot/three/upstream.json. Do not edit manually.
// </auto-generated>

/**
 * Provenance of the Three.js build shipped in this package.
 * Only identity fields are exposed; the internal file layout is intentionally not part of this module.
 */
export const upstream = Object.freeze({
  name: 'three',
  version: '$version',
  revision: '$revision',
  commit: '$commit',
  license: '$license',
  repository: '$repository',
});

"@ -replace "`r`n", "`n"

$utf8NoBom = New-Object System.Text.UTF8Encoding($false)
$drift = New-Object System.Collections.Generic.List[string]

function Sync-Bytes([string]$sourcePath, [string]$targetPath) {
    $same = (Test-Path $targetPath) -and
        ((Get-FileHash $sourcePath -Algorithm SHA256).Hash -eq (Get-FileHash $targetPath -Algorithm SHA256).Hash)
    if ($same) { return }
    if ($Check) { $drift.Add($targetPath); return }
    New-Item -ItemType Directory -Force -Path (Split-Path $targetPath) | Out-Null
    Copy-Item -LiteralPath $sourcePath -Destination $targetPath -Force
}

function Sync-Text([string]$content, [string]$targetPath) {
    $same = (Test-Path $targetPath) -and ([System.IO.File]::ReadAllText($targetPath) -ceq $content)
    if ($same) { return }
    if ($Check) { $drift.Add($targetPath); return }
    New-Item -ItemType Directory -Force -Path (Split-Path $targetPath) | Out-Null
    [System.IO.File]::WriteAllText($targetPath, $content, $utf8NoBom)
}

foreach ($file in $files) {
    Sync-Bytes $file.SourcePath (Join-Path $threeTarget $file.Target)
}
Sync-Bytes (Join-Path $upstreamRoot 'LICENSE') (Join-Path $threeTarget 'LICENSE')
Sync-Text $json (Join-Path $threeTarget 'upstream.json')
Sync-Text $js (Join-Path $jsTarget 'three-upstream.js')

if ($Check) {
    if ($drift.Count -gt 0) {
        $drift | ForEach-Object { Write-Error "Drift: $_" -ErrorAction Continue }
        exit 1
    }
    Write-Host "Three.js runtime assets match lib/three.js @ $commit ($describe)."
}
else {
    Write-Host "Synced Three.js $version (r$revision) from lib/three.js @ $commit."
}

